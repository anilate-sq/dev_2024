#include <iostream>

using namespace std;

int main(){
    // Арифмитические операции
    // + -> сложение
    // - -> вычетание
    // / -> деление
    // * -> умножение
    // % -> остаток от деления

    cout << 2 + 2 << endl; // Сложение
    cout << 2 - 2 << endl; // Вычетание
    cout << 2 / 2 << endl; // Деление
    cout << 2 * 2 << endl; // Умножение
    cout << 2 % 2 << endl; // Остаток от деления
}