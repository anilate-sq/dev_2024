// Оператор new означает, что мы выделяем память в heap и записываем туда указанное значение
#include <iostream>
using namespace std;

int main(){
    // Способ 1. Значение не инициализированно
    int* p = new int;
    *p = 1225;
    cout << *p << endl;
    
    // Способ 2. Значение инициализированно
    int* np = new int(1225);  
    cout << *np << endl;

    // Всегда нужно прописывать delete по завершению работы
}