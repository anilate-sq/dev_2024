// Ссылки
#include <iostream>

using namespace std;

int main(){
    // Ссылка - именованая переменная, ссылающаяся на значение другой переменной 

    int a = 10;
    int& b = a; // b и a одна и таже переменная
    cout << "Изначальное значение a: " << a << endl;
    b += 10;
    cout << "Первое изменение a: " << a << endl;
    b -= 15;
    cout << "Второе изменение a: " << a << endl;
}